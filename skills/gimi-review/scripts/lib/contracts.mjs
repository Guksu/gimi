/**
 * 계약 파일의 영향 범위(설계 결정 47) — 프론트·백엔드는 계약 파일로만 잇는다.
 * OpenAPI는 옛 판·새 판을 비교해 바뀐 엔드포인트·필드를 뽑고, 쓰는 곳을 두 가지로 찾는다.
 *   - 생성 타입(openapi-typescript·orval 등)이 있으면 바뀐 필드·스키마를 TypeScript 참조로 찾는다(정확).
 *   - 바뀐 엔드포인트(필드가 바뀐 스키마를 쓰는 엔드포인트 포함)의 경로를 문자열로 찾는다(정확도 낮음).
 * GraphQL은 저장소의 스키마 파일 전체를 합쳐 비교하고, 코드 안의 연산을 스키마로 풀어 바뀐 필드를 고르는 곳을 찾는다.
 * 지운 필드는 옛 스키마로 푼다. 더하기만 한 변경은 아직 쓰는 곳이 없으니 찾지 않는다.
 * 함께 보는 저장소(설계 결정 57)가 있으면 그 저장소에서도 같은 방법으로 찾고, 사용처에 repo를 붙인다.
 */
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { attempt } from './exec.mjs'
import { diffSchema, extractDocuments, hasTypeDefinitions, parseDocument, parseSchema, resolveOperations } from './graphql.mjs'
import { CODE_GLOBS, createFileReader, createTsIndex, finalize, grep, lineOfPos, usageAt } from './impact.mjs'
import { diffOpenApi, isOpenApi } from './openapi.mjs'
import { YamlUnsupported } from './yaml.mjs'

const OPENAPI_FILE = /\.(?:ya?ml|json)$/i
// YAML은 줄 앞, JSON은 { 또는 , 뒤에 openapi·swagger 키가 온다
const OPENAPI_MARK = /(?:^\s*|[{,]\s*)["']?(?:openapi|swagger)["']?\s*:/m
const GRAPHQL_FILE = /\.(?:graphqls?|gql)$/i
const CODE = /\.(?:m|c)?[jt]sx?$|\.(?:vue|svelte)$/
// 생성 타입의 머리 글 — 이 파일들은 계약에서 만든 것이다
const OPENAPI_GENERATED = ['auto-generated by openapi-typescript', 'Generated by orval', 'OpenAPI Generator', 'swagger-typescript-api']
const GRAPHQL_GENERATED = ['export type Scalars = {']
// 사용처를 찾는 바뀜의 수 — 깨질 수 있음·확인부터
const MAX_SEARCHED = 20
const MAX_DOCUMENT_FILES = 2000

const show = (exec, rev, path) => attempt(() => exec.git(['show', `${rev}:${path}`]))

/** 생성 타입 안에서 스키마(와 필드) 선언의 이름 위치 — interface Order·type Order = {…}·schemas: { Order: {…} } */
const memberPos = ({ ts, text, fileName, schema, field }) => {
  const source = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true)
  const nameOf = (node) => (node.name && (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name)) ? node.name.text : null)
  const membersOf = (node) => {
    if (ts.isInterfaceDeclaration(node)) return node.members
    const type = node.type
    return type && ts.isTypeLiteralNode(type) ? type.members : null
  }
  let found = null
  const visit = (node) => {
    if (found !== null) return
    if ((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node) || ts.isPropertySignature(node)) && nameOf(node) === schema) {
      if (!field) {
        found = node.name.getStart(source)
        return
      }
      const member = (membersOf(node) ?? []).find((m) => nameOf(m) === field)
      if (member) {
        found = member.name.getStart(source)
        return
      }
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  return found
}

const parseOpenApiText = ({ path, text, yaml }) => {
  if (text == null) return null
  if (/\.json$/i.test(path)) return JSON.parse(text)
  return yaml.parse(text)
}

/** 바뀐 엔드포인트 경로로 찾을 문자열 — 경로 그대로, 경로 변수 앞까지(/orders/{id} → /orders/) */
const pathPatterns = (endpoint) => {
  const path = endpoint.slice(endpoint.indexOf(' ') + 1)
  const out = [path]
  const brace = path.indexOf('{')
  if (brace > 0) out.push(path.slice(0, brace))
  return out.filter((pattern) => /[A-Za-z]/.test(pattern) && pattern.length >= 3)
}

/**
 * @param {{ exec: any, root: string, scope: { mergeBase: string }, files: import('./diff.mjs').FileDiff[], ts: any, yaml: { parse: (text: string) => any, name: string }, linked?: { label: string, root: string, exec: any, ts: any }[] }} args
 * @returns {{ contracts: any[], skipped: { context: string, reason: string }[], notes: string[] }}
 */
export const collectContracts = ({ exec, root, scope, files, ts, yaml, linked = [] }) => {
  const contracts = []
  const skipped = []
  const notes = []
  const changedPaths = new Set(files.map((file) => file.newPath).filter(Boolean))
  const grepFilesIn = (target, patterns) => {
    if (patterns.length === 0) return []
    const out = attempt(() => target.exec.git(['grep', '-l', '-I', '-F', ...patterns.flatMap((p) => ['-e', p]), '--', ...CODE_GLOBS]))
    return out ? out.split('\n').filter(Boolean) : []
  }
  // 사용처를 찾는 곳 — 리뷰하는 저장소와 함께 보는 저장소. 함께 보는 저장소의 것은 이 변경에서 바뀌지 않았다
  const targets = [{ repo: null, root, exec, ts, changedPaths }, ...linked.map((l) => ({ repo: l.label, root: l.root, exec: l.exec, ts: l.ts, changedPaths: new Set() }))].map((target) => ({
    ...target,
    readLines: createFileReader({ root: target.root }),
    index: target.ts ? createTsIndex({ ts: target.ts, root: target.root }) : null,
    openApiGenerated: null,
  }))
  const [self] = targets
  const grepFiles = (patterns) => grepFilesIn(self, patterns)
  const usageIn = (target, path, line) => {
    const usage = usageAt({ readLines: target.readLines, path, line, changedPaths: target.changedPaths })
    return target.repo === null ? usage : { ...usage, repo: target.repo }
  }
  const regenerated = ({ contractPath, generated }) => {
    if (generated.length > 0 && !generated.some((path) => changedPaths.has(path))) {
      notes.push(`계약 파일(${contractPath})이 바뀌었는데 생성 타입(${generated.slice(0, 3).join(', ')})은 이 변경에서 바뀌지 않았다 — 다시 생성했는지 확인한다`)
    }
  }

  for (const file of files) {
    const path = file.newPath ?? file.oldPath
    if (file.binary) continue
    if (/\.proto$/i.test(path)) skipped.push({ context: '영향 범위', reason: `proto 계약(${path})은 아직 읽지 않는다 — 생성된 코드의 사용처는 직접 찾는다` })
    // 서버 코드 안의 스키마(gql typeDefs)는 계약으로 읽지 않는다 — 스키마 파일만 읽는다
    if (CODE.test(path) && file.status !== 'deleted') {
      const after = show(exec, 'HEAD', file.newPath)
      if (after && extractDocuments({ path, text: after }).some((doc) => /\b(?:extend\s+)?type\s+(?:Query|Mutation)\b/.test(doc.text))) {
        notes.push(`${path} 안의 GraphQL 스키마(gql typeDefs)는 계약으로 읽지 않았다 — 스키마 파일(.graphql)만 비교한다`)
      }
    }
  }

  // OpenAPI — 파일마다 따로 비교한다
  let openApiGenerated = null
  for (const file of files) {
    const path = file.newPath ?? file.oldPath
    if (file.binary || !OPENAPI_FILE.test(path)) continue
    const beforeText = file.status === 'added' ? null : show(exec, scope.mergeBase, file.oldPath)
    const afterText = file.status === 'deleted' ? null : show(exec, 'HEAD', file.newPath)
    if (!OPENAPI_MARK.test(beforeText ?? '') && !OPENAPI_MARK.test(afterText ?? '')) continue
    let before
    let after
    try {
      before = parseOpenApiText({ path, text: beforeText, yaml })
      after = parseOpenApiText({ path, text: afterText, yaml })
    } catch (error) {
      const reason = error instanceof YamlUnsupported ? error.message : `${error.message}`.split('\n')[0]
      skipped.push({ context: '영향 범위', reason: `계약 파일 ${path}을(를) 읽지 못했다 — ${reason}` })
      continue
    }
    if (!isOpenApi(before) && !isOpenApi(after)) continue
    for (const target of targets) target.openApiGenerated ??= grepFilesIn(target, OPENAPI_GENERATED)
    const generated = self.openApiGenerated
    const changes = diffOpenApi({ before: isOpenApi(before) ? before : {}, after: isOpenApi(after) ? after : {} })
    const pathCache = new Map()
    const pathUsages = (target, endpoint) => {
      const key = `${target.repo ?? ''}\0${endpoint}`
      if (!pathCache.has(key)) {
        const patterns = pathPatterns(endpoint)
        // 계약 파일과 생성 타입 자신은 사용처가 아니다
        const excluded = [...(target === self ? [path] : []), ...target.openApiGenerated].map((p) => `:(exclude)${p}`)
        const hits = patterns.length === 0 ? [] : grep({ exec: target.exec, args: ['-F', ...patterns.flatMap((p) => ['-e', p]), '--', ...CODE_GLOBS, ...excluded] })
        pathCache.set(key, hits.map((hit) => usageIn(target, hit.path, hit.line)))
      }
      return pathCache.get(key)
    }
    let searched = 0
    const enriched = changes.map((change) => {
      if (change.level === 'additive' || searched >= MAX_SEARCHED) return { ...change, method: null, searched: false, total: 0, unchanged: 0, usages: [] }
      searched += 1
      const endpoints = change.target === 'endpoint' ? [change.key] : (change.endpoints ?? [])
      let usages = targets.flatMap((target) => endpoints.flatMap((endpoint) => pathUsages(target, endpoint)))
      let method = 'text'
      // 생성 타입이 있으면 바뀐 스키마·필드를 TypeScript 참조로도 찾는다 — 함께 보는 저장소의 생성 타입은 옛 계약에서 만든 것이라 옛 필드가 있다
      for (const target of targets) {
        if (!target.index || change.target !== 'schema') continue
        for (const genPath of target.openApiGenerated) {
          const abs = join(target.root, genPath)
          if (!existsSync(abs)) continue
          const pos = memberPos({ ts: target.ts, text: readFileSync(abs, 'utf8'), fileName: abs, schema: change.schema, field: change.field })
          if (pos === null) continue
          const refs = target.index.referencesOf({ path: genPath, namePos: pos })
          if (!refs) continue
          method = 'typescript+text'
          usages = [...usages, ...refs.map((ref) => usageIn(target, ref.path, lineOfPos({ readLines: target.readLines, path: ref.path, pos: ref.pos })))]
        }
      }
      return { ...change, method, searched: true, ...finalize(usages.filter((u) => !/^\s*import\b/.test(u.text))) }
    })
    contracts.push({ kind: 'openapi', path, parser: /\.json$/i.test(path) ? 'json' : yaml.name, generated, changes: enriched })
    regenerated({ contractPath: path, generated })
  }

  // GraphQL — 저장소의 스키마 파일을 모두 합쳐 옛 판·새 판을 비교한다
  const changedSdl = files.filter((file) => !file.binary && GRAPHQL_FILE.test(file.newPath ?? file.oldPath))
  if (changedSdl.length > 0) {
    const sourcesAt = (rev) => {
      const listed = attempt(() => exec.git(['ls-tree', '-r', '-z', '--name-only', rev])) ?? ''
      const out = []
      for (const path of listed.split('\0').filter((p) => GRAPHQL_FILE.test(p))) {
        const text = show(exec, rev, path)
        const definitions = attempt(() => parseDocument(text ?? ''))
        if (definitions && hasTypeDefinitions(definitions)) out.push({ path, text })
      }
      return out
    }
    const oldSources = sourcesAt(scope.mergeBase)
    const newSources = sourcesAt('HEAD')
    const schemaPaths = new Set([...oldSources, ...newSources].map((s) => s.path))
    const changedSchema = changedSdl.map((file) => file.newPath ?? file.oldPath).filter((path) => schemaPaths.has(path))
    if (changedSchema.length > 0) {
      let before
      let after
      try {
        before = parseSchema(oldSources)
        after = parseSchema(newSources)
      } catch (error) {
        skipped.push({ context: '영향 범위', reason: `GraphQL 스키마를 읽지 못했다 — ${error.message}` })
      }
      if (before && after) {
        // 연산 문서 — gql 템플릿이 있는 코드와 스키마가 아닌 .graphql 파일. 함께 보는 저장소에서도 모은다
        let documentCount = 0
        const uses = []
        for (const target of targets) {
          const candidates = [
            ...grepFilesIn(target, ['gql', 'graphql', 'GraphQL']),
            ...(attempt(() => target.exec.git(['ls-files', '-z', '--', '*.graphql', '*.gql'])) ?? '').split('\0').filter((p) => p && !(target === self && schemaPaths.has(p))),
          ].slice(0, MAX_DOCUMENT_FILES)
          const documents = candidates.flatMap((path) => {
            const abs = join(target.root, path)
            return existsSync(abs) ? extractDocuments({ path, text: readFileSync(abs, 'utf8') }) : []
          })
          documentCount += documents.length
          const resolvedNew = resolveOperations({ schema: after, documents })
          const resolvedOld = resolveOperations({ schema: before, documents })
          const own = [...new Map([...resolvedNew.uses, ...resolvedOld.uses].map((u) => [`${u.path}:${u.line}:${u.typeName}.${u.fieldName}`, u])).values()]
          uses.push(...own.map((u) => ({ ...u, target })))
          for (const error of resolvedNew.errors.slice(0, 3)) notes.push(target.repo === null ? error : `${target.repo}: ${error}`)
        }
        const generated = grepFiles(GRAPHQL_GENERATED)
        let searched = 0
        const changes = diffSchema({ before, after }).map((change) => {
          if (change.level === 'additive' || searched >= MAX_SEARCHED) return { ...change, method: null, searched: false, total: 0, unchanged: 0, usages: [] }
          searched += 1
          const targets = new Set(change.affects)
          const found = uses
            .filter((u) => targets.has(`${u.typeName}.${u.fieldName}`))
            .map((u) => ({ ...usageIn(u.target, u.path, u.line), operation: u.operation, fieldPath: u.fieldPath }))
          return { ...change, method: 'graphql', searched: true, ...finalize(found) }
        })
        const label = changedSchema.length > 2 ? `${changedSchema.slice(0, 2).join(', ')} 외 ${changedSchema.length - 2}개` : changedSchema.join(', ')
        contracts.push({ kind: 'graphql', path: label, sources: [...schemaPaths].sort(), generated, documents: documentCount, changes })
        regenerated({ contractPath: label, generated })
      }
    }
  }
  return { contracts, skipped, notes }
}
