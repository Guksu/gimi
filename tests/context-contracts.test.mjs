import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { tmpdir } from 'node:os'
import ts from 'typescript'
import { collectContext } from '../skills/gimi-review/scripts/lib/collect.mjs'
import { renderSummary } from '../skills/gimi-review/scripts/lib/summary.mjs'
import { execFor, makeRepo } from './helpers/repo.mjs'

const TSCONFIG = JSON.stringify({ compilerOptions: { strict: true, target: 'ES2022', module: 'ESNext', moduleResolution: 'Bundler', noEmit: true, skipLibCheck: true }, include: ['src'] })
const withTs = () => ({ ts, reason: null })
const withoutTs = () => ({ ts: null, reason: '이 프로젝트에 typescript가 없다' })

/** 처음 커밋(main) → 브랜치에서 바꾼 커밋. 맥락 묶음을 돌려준다 */
const run = ({ base, changed, loadTs = withoutTs }) => {
  const repo = makeRepo()
  try {
    repo.write(base)
    repo.commit('feat: 처음')
    repo.git('switch', '-q', '-c', 'feat/api')
    for (const [path, text] of Object.entries(changed)) {
      if (text === null) repo.remove(path)
      else repo.write({ [path]: text })
    }
    repo.commit('feat: 계약 바꿈')
    return collectContext({ exec: execFor({ dir: repo.dir }), useGh: false, loadTs })
  } finally {
    repo.cleanup()
  }
}
const changeOf = (contract, key) => contract.changes.find((c) => c.key === key)
const where = (change) => change.usages.map((u) => `${u.path}:${u.line}`)

const OPENAPI = (totalAmount) => `openapi: 3.0.3
info:
  title: shop
  version: 1.0.0
paths:
  /orders/{id}:
    get:
      parameters:
        - name: id
          in: path
          required: true
          schema:
            type: string
      responses:
        '200':
          description: ok
          content:
            application/json:
              schema:
                $ref: '#/components/schemas/Order'
  /health:
    get:
      responses:
        '200':
          description: ok
components:
  schemas:
    Order:
      type: object
      properties:
        id:
          type: string
${totalAmount}`

describe('계약 파일 — OpenAPI', () => {
  const base = {
    'api/openapi.yaml': OPENAPI('        totalAmount:\n          type: integer\n'),
    'src/api.js': "export const getOrder = (id) => fetch('/orders/' + id)\nexport const typed = (client) => client.GET('/orders/{id}')\n",
    'src/other.js': "export const health = () => fetch('/health')\n",
  }

  it('바뀐 필드·엔드포인트를 깨질 수 있음부터 적고, 그 필드를 쓰는 엔드포인트의 경로를 문자열로 찾는다', () => {
    const context = run({ base, changed: { 'api/openapi.yaml': OPENAPI('') } })
    const [contract] = context.impact.contracts
    assert.deepEqual([contract.kind, contract.path, contract.parser], ['openapi', 'api/openapi.yaml', '내장'])
    const change = changeOf(contract, 'Order.totalAmount')
    assert.deepEqual([change.change, change.level, change.endpoints], ['removed', 'breaking', ['GET /orders/{id}']])
    assert.equal(change.method, 'text')
    assert.deepEqual(where(change), ['src/api.js:1', 'src/api.js:2'])
    assert.equal(context.skipped.some((s) => /계약 파일/.test(s.reason)), false)
  })

  it('생성 타입(openapi-typescript)이 있으면 바뀐 필드를 TypeScript 참조로 찾고, 생성 타입을 다시 만들지 않았으면 알린다', () => {
    const generated = '/**\n * This file was auto-generated by openapi-typescript.\n */\nexport interface components {\n  schemas: {\n    Order: {\n      id: string\n      totalAmount: number\n    }\n  }\n}\n'
    const context = run({
      base: { ...base, 'tsconfig.json': TSCONFIG, 'src/schema.d.ts': generated, 'src/total.ts': "import type { components } from './schema'\nexport const total = (o: components['schemas']['Order']) => o.totalAmount\n" },
      changed: { 'api/openapi.yaml': OPENAPI('        totalAmount:\n          type: string\n') },
      loadTs: withTs,
    })
    const [contract] = context.impact.contracts
    const change = changeOf(contract, 'Order.totalAmount')
    assert.equal(change.method, 'typescript+text')
    assert.ok(where(change).includes('src/total.ts:2'), where(change).join(', '))
    assert.deepEqual(contract.generated, ['src/schema.d.ts'])
    assert.ok(context.impact.notes.some((n) => /api\/openapi\.yaml.*생성 타입\(src\/schema\.d\.ts\).*다시 생성했는지/.test(n)))
  })

  it('더하기만 한 변경은 사용처를 찾지 않는다. JSON 문서도 읽는다', () => {
    const doc = (extra) => JSON.stringify({ openapi: '3.0.0', paths: { '/health': { get: { responses: { 200: { description: 'ok' } } } }, ...extra } })
    const context = run({ base: { 'api/openapi.json': doc({}) }, changed: { 'api/openapi.json': doc({ '/coupons': { get: { responses: { 200: { description: 'ok' } } } } }) } })
    const [contract] = context.impact.contracts
    assert.equal(contract.parser, 'json')
    const change = changeOf(contract, 'GET /coupons')
    assert.deepEqual([change.level, change.searched], ['additive', false])
  })

  it('내장 파서가 읽지 못하는 YAML(앵커 등)은 건너뜀에 이유와 함께 적는다', () => {
    const context = run({ base: { 'api/openapi.yaml': 'openapi: 3.0.0\npaths: {}\n' }, changed: { 'api/openapi.yaml': 'openapi: 3.0.0\nx: &a 1\npaths: {}\n' } })
    assert.deepEqual(context.impact.contracts, [])
    assert.ok(context.skipped.some((s) => s.context === '영향 범위' && /api\/openapi\.yaml을\(를\) 읽지 못했다.*앵커/.test(s.reason)))
  })
})

describe('계약 파일 — GraphQL', () => {
  const schema = (amount) => `type Query {\n  order(id: ID!): Order\n  cart: Cart\n}\ntype Order {\n  id: ID!\n  totalAmount: ${amount}\n}\ntype Cart {\n  totalAmount: Int!\n}\n`
  const base = {
    'schema.graphql': schema('Int!'),
    'src/order.js': "import { gql } from '@apollo/client'\nexport const GET_ORDER = gql`\n  query GetOrder($id: ID!) {\n    order(id: $id) {\n      id\n      totalAmount\n    }\n  }\n`\n",
    'src/cart.js': "import { gql } from '@apollo/client'\nexport const GET_CART = gql`query GetCart { cart { totalAmount } }`\n",
    'src/fragments.graphql': 'fragment OrderTotal on Order { totalAmount }\n',
  }

  it('바뀐 필드를 고르는 연산만 찾는다 — 이름이 같은 다른 타입의 필드(Cart.totalAmount)는 섞지 않는다', () => {
    const context = run({ base, changed: { 'schema.graphql': schema('Int') } })
    const [contract] = context.impact.contracts
    assert.deepEqual([contract.kind, contract.path], ['graphql', 'schema.graphql'])
    const change = changeOf(contract, 'Order.totalAmount')
    assert.deepEqual([change.level, change.method], ['caution', 'graphql'])
    assert.deepEqual(where(change), ['src/fragments.graphql:1', 'src/order.js:6'])
    assert.deepEqual(change.usages.map((u) => u.operation), ['fragment OrderTotal', 'query GetOrder'])
  })

  it('지운 필드는 옛 스키마로 풀어 그 필드를 고르던 연산을 찾는다', () => {
    const context = run({ base, changed: { 'schema.graphql': 'type Query {\n  order(id: ID!): Order\n  cart: Cart\n}\ntype Order {\n  id: ID!\n}\ntype Cart {\n  totalAmount: Int!\n}\n' } })
    const change = changeOf(context.impact.contracts[0], 'Order.totalAmount')
    assert.deepEqual([change.change, change.level], ['removed', 'breaking'])
    assert.deepEqual(where(change), ['src/fragments.graphql:1', 'src/order.js:6'])
  })

  it('요약에 계약 절을 쓴다 — 바뀐 것과 등급, diff 밖 사용처', () => {
    const context = run({ base, changed: { 'schema.graphql': schema('Int') } })
    const text = renderSummary({ context, outPath: null })
    assert.match(text, /^계약 {6}바뀐 계약 1개 — 깨질 수 있음 0 · 확인 1 · 추가 0$/m)
    assert.match(text, /^ {2}schema\.graphql \(GraphQL\) — 바뀐 것 1$/m)
    assert.match(text, /^ {4}Order\.totalAmount {2}확인 — 타입 Int! → Int\(null을 허용하게 됐다\) {2}연산 2\(이 변경에서 안 바뀜 2\)$/m)
    assert.match(text, /^ {6}src\/order\.js:6 {2}query GetOrder › order\.totalAmount$/m)
  })
})

describe('계약 파일 — 함께 보는 저장소(결정 57)', () => {
  /** 백엔드 저장소(리뷰하는 곳)에서 계약을 바꾸고, 프론트 저장소는 linkedRepos로 함께 본다 */
  const runLinked = ({ base, changed, web, loadTs = withoutTs, linkedRepos }) => {
    const front = makeRepo()
    front.write(web)
    front.commit('feat: 화면')
    const repo = makeRepo()
    try {
      repo.write(base)
      repo.commit('feat: 처음')
      repo.git('switch', '-q', '-c', 'feat/api')
      repo.write(changed)
      repo.commit('feat: 계약 바꿈')
      const context = collectContext({ exec: execFor({ dir: repo.dir }), useGh: false, loadTs, linkedRepos: linkedRepos ?? [front.dir] })
      return { context, front: front.dir }
    } finally {
      repo.cleanup()
      front.cleanup()
    }
  }
  const generated = '/**\n * This file was auto-generated by openapi-typescript.\n */\nexport interface components {\n  schemas: {\n    Order: {\n      id: string\n      totalAmount: number\n    }\n  }\n}\n'

  it('OpenAPI — 바뀐 필드를 쓰는 엔드포인트의 경로와 생성 타입의 참조를 함께 보는 저장소에서도 찾고, 어느 저장소인지 붙인다', () => {
    const { context, front } = runLinked({
      base: { 'api/openapi.yaml': OPENAPI('        totalAmount:\n          type: integer\n'), 'src/server.js': "export const route = '/orders/'\n" },
      changed: { 'api/openapi.yaml': OPENAPI('') },
      web: { 'tsconfig.json': TSCONFIG, 'src/schema.d.ts': generated, 'src/api.js': "export const getOrder = (id) => fetch('/orders/' + id)\n", 'src/total.ts': "import type { components } from './schema'\nexport const total = (o: components['schemas']['Order']) => o.totalAmount\n" },
      loadTs: withTs,
    })
    const change = changeOf(context.impact.contracts[0], 'Order.totalAmount')
    const linked = change.usages.filter((u) => u.repo === front).map((u) => [`${u.path}:${u.line}`, u.changedInPr])
    assert.deepEqual(linked, [['src/api.js:1', false], ['src/total.ts:2', false]])
    assert.equal(change.method, 'typescript+text')
    // 리뷰하는 저장소의 사용처에는 repo를 붙이지 않는다
    assert.deepEqual(change.usages.filter((u) => !('repo' in u)).map((u) => `${u.path}:${u.line}`), ['src/server.js:1'])
    assert.ok(context.impact.notes.some((n) => n.includes(`함께 보는 저장소 ${front}`) && /지금 체크아웃된 커밋 [0-9a-f]{7}/.test(n)), context.impact.notes.join('\n'))
  })

  it('GraphQL — 바뀐 필드를 고르는 함께 보는 저장소의 연산을 찾는다', () => {
    const schema = (amount) => `type Query {\n  order(id: ID!): Order\n}\ntype Order {\n  id: ID!\n  totalAmount: ${amount}\n}\n`
    const { context, front } = runLinked({
      base: { 'schema.graphql': schema('Int!') },
      changed: { 'schema.graphql': schema('Int') },
      web: { 'src/order.js': "import { gql } from '@apollo/client'\nexport const GET_ORDER = gql`\n  query GetOrder($id: ID!) {\n    order(id: $id) {\n      totalAmount\n    }\n  }\n`\n" },
    })
    const change = changeOf(context.impact.contracts[0], 'Order.totalAmount')
    assert.deepEqual(change.usages.map((u) => [u.repo, `${u.path}:${u.line}`, u.operation]), [[front, 'src/order.js:5', 'query GetOrder']])
  })

  it('찾을 수 없는 경로나 git 저장소가 아닌 곳은 건너뜀에 적는다', () => {
    const { context } = runLinked({
      base: { 'api/openapi.yaml': OPENAPI('        totalAmount:\n          type: integer\n') },
      changed: { 'api/openapi.yaml': OPENAPI('') },
      web: { 'src/api.js': '' },
      linkedRepos: ['../없는-저장소', tmpdir()],
    })
    const reasons = context.skipped.filter((s) => s.context === '영향 범위').map((s) => s.reason)
    assert.ok(reasons.some((r) => r.includes('../없는-저장소') && /찾지 못했다/.test(r)), reasons.join('\n'))
    assert.ok(reasons.some((r) => r.includes(tmpdir()) && /git 저장소가 아니다/.test(r)), reasons.join('\n'))
  })

  it('요약은 함께 보는 저장소의 사용처 앞에 저장소를 적는다', () => {
    const { context, front } = runLinked({
      base: { 'api/openapi.yaml': OPENAPI('        totalAmount:\n          type: integer\n') },
      changed: { 'api/openapi.yaml': OPENAPI('') },
      web: { 'src/api.js': "export const getOrder = (id) => fetch('/orders/' + id)\n" },
    })
    assert.ok(renderSummary({ context, outPath: null }).includes(`[${front}] src/api.js:1`))
  })
})

describe('계약 파일 — 없음', () => {
  it('계약 파일이 바뀌지 않았으면 계약은 빈 목록이고 요약에 절을 쓰지 않는다', () => {
    const context = run({ base: { 'src/a.js': 'export const a = 1\n' }, changed: { 'src/a.js': 'export const a = 2\n' } })
    assert.deepEqual(context.impact.contracts, [])
    assert.doesNotMatch(renderSummary({ context, outPath: null }), /^계약/m)
  })
})
